package server

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"watchcow/internal/app"
	"watchcow/internal/docker"
	"watchcow/internal/fpkgen"
)

// AdoptInstalled imports existing WatchCow-generated packages, including custom
// package IDs and containers that are currently stopped. Other fnOS apps are
// excluded by the generated control-script signature and container ownership.
func AdoptInstalled(ctx context.Context, monitor *docker.Monitor, storage *DashboardStorage, appsDir string) error {
	containers, err := monitor.Inventory(ctx)
	if err != nil {
		return err
	}
	byName := map[string]docker.ContainerInfo{}
	for _, ctr := range containers {
		byName[ctr.Name] = ctr
	}
	dirs, err := os.ReadDir(appsDir)
	if err != nil {
		return err
	}
	for _, dir := range dirs {
		id := dir.Name()
		if id == "watchcow" || id == "watchcow-r" {
			continue
		}
		cmd, err := os.ReadFile(filepath.Join(appsDir, id, "cmd", "main"))
		if err != nil {
			continue
		}
		if !strings.Contains(string(cmd), "Generated by WatchCow") {
			continue
		}
		match := regexp.MustCompile(`(?m)^# Container: (.+)$`).FindStringSubmatch(string(cmd))
		if len(match) != 2 {
			continue
		}
		ctr, ok := byName[strings.TrimSpace(match[1])]
		if !ok {
			continue
		}
		data, err := os.ReadFile(filepath.Join(appsDir, id, "target", "ui", "config"))
		if err != nil {
			return err
		}
		var ui struct {
			Entries map[string]struct {
				Title     string   `json:"title"`
				Protocol  string   `json:"protocol"`
				Port      string   `json:"port"`
				Path      string   `json:"url"`
				Type      string   `json:"type"`
				AllUsers  bool     `json:"allUsers"`
				NoDisplay bool     `json:"noDisplay"`
				FileTypes []string `json:"fileTypes"`
			} `json:".url"`
		}
		if err := json.Unmarshal(data, &ui); err != nil {
			return fmt.Errorf("导入 %s: %w", id, err)
		}
		// On later starts, desired stored/label configs reconstruct entries.
		// A migrated CGI URL cannot be interpreted as an upstream service.
		var entries []StoredEntry
		for entryID, e := range ui.Entries {
			name := ""
			if entryID != id {
				if !strings.HasPrefix(entryID, id+".") {
					continue
				}
				name = strings.TrimPrefix(entryID, id+".")
			}
			if strings.HasPrefix(e.Path, "/cgi/ThirdParty/") {
				continue
			}
			entries = append(entries, StoredEntry{Name: name, Title: e.Title, Protocol: e.Protocol, Port: e.Port, Path: e.Path, UIType: e.Type, AllUsers: e.AllUsers, NoDisplay: e.NoDisplay, FileTypes: e.FileTypes})
		}
		key := NewContainerKeyForContainer(ctr.Image, ctr.Name, ctr.IdentityPorts)
		if len(entries) > 0 && ctr.Labels["watchcow.enable"] != "true" && !storage.Has(key) {
			if err := storage.Set(&StoredConfig{Key: key, AppName: id, DisplayName: ctr.Name, Version: "1.0.0", Entries: entries}); err != nil {
				return err
			}
		}
		if stored := storage.Get(key); stored != nil {
			entries = stored.Entries
		}
		a := &app.App{AppName: id, ContainerID: ctr.ID, ContainerName: ctr.Name, Image: ctr.Image, Labels: ctr.Labels, Status: app.StatusStopped}
		if ctr.State == "running" {
			a.Status = app.StatusRunning
		}
		// Parse labels for entries that already use a CGI launcher, and preserve
		// named/redirect semantics through the monitor's normal parsing path.
		if ctr.Labels["watchcow.enable"] == "true" {
			a.Entries = fpkgen.ParseEntries(ctr.Labels, ctr.Name, "", firstHostPort(ctr.Ports))
		} else {
			for _, e := range entries {
				a.Entries = append(a.Entries, app.Entry{Name: e.Name, Title: e.Title, Protocol: e.Protocol, Port: e.Port, Path: e.Path, UIType: e.UIType, AllUsers: e.AllUsers, NoDisplay: e.NoDisplay, FileTypes: e.FileTypes, Redirect: e.Redirect, ForceExternal: e.ForceExternal})
			}
		}
		monitor.AdoptApp(a)
	}
	return nil
}
