func desktopFixture(t *testing.T) (*DesktopMigrator, string) {
	t.Helper()
	dir := t.TempDir()
	apps := filepath.Join(dir, "apps")
	id := "watchcow.demo"
	live := filepath.Join(apps, id)
	engine, err := fpkgen.NewTemplateEngine()
	if err != nil {
		t.Fatal(err)
	}
	main, err := engine.Render("cmd_main.tmpl", &fpkgen.TemplateData{ContainerName: "Demo"})
	if err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(live, "cmd/main"), main)
	write(t, filepath.Join(live, "cmd/install_callback"), []byte("#!/bin/bash\n# Generated by WatchCow\nexit 0\n"))
	write(t, filepath.Join(live, "config/resource"), []byte("{}"))
	write(t, filepath.Join(live, "config/privilege"), []byte(`{"defaults":{"run-as":"root"}}`))
	write(t, filepath.Join(live, "manifest"), []byte("appname=watchcow.demo\nversion=1.0.0\ndesktop_uidir=ui\ninstall_type=root\n"))
	write(t, filepath.Join(live, "target/ui/config"), []byte(`{".url":{"watchcow.demo":{"title":"My Demo","protocol":"","url":"/cgi/ThirdParty/watchcow.demo/index.cgi/proxy/watchcow.demo/_","allUsers":true}}}`))
	write(t, filepath.Join(live, "target/ui/index.cgi"), []byte("#!/bin/sh\nexec /var/apps/watchcow-r/target/watchcow-r --mode cgi\n"))
	return &DesktopMigrator{Dir: filepath.Join(dir, "etc"), AppsDir: apps, VolumeReady: func(int) error { return nil }}, id
}

func fakeDesktopRun(t *testing.T, d *DesktopMigrator, installed *bool, calls *int, fail *bool) func(context.Context, string, ...string) ([]byte, error) {
	t.Helper()
	return func(ctx context.Context, command string, args ...string) ([]byte, error) {
		if command == "runuser" {
			sql := args[len(args)-1]
			switch {
			case strings.Contains(sql, "row_to_json(a)"):
				if strings.Contains(sql, "is_uninstall=") {
					t.Fatal("capability flag used as installed state")
				}
				return []byte(`{"install_volume_id":2,"is_stop":true,"is_uninstall":true,"status":"stopped"}`), nil
			case strings.Contains(sql, "user_desktop_entry"):
				return []byte(`[{"app_name":"watchcow.demo","parent_id":50,"sort":150}]`), nil
			case strings.Contains(sql, "FROM entry"):
				url := `{"protocol":"http","port":"8096","path":"/"}`
				if *installed {
					url = `{"path":"/cgi/ThirdParty/watchcow.demo/index.cgi/proxy/watchcow.demo/_"}`
				}
				b, _ := json.Marshal([]desktopRegistration{{Name: "watchcow.demo", URL: url}})
				return b, nil
			default:
				t.Fatalf("unexpected query: %s", sql)
			}
		}
		if command != "appcenter-cli" {
			t.Fatalf("unexpected command %s", command)
		}
		*calls++
		joined := strings.Join(args, " ")
		if !strings.Contains(joined, "--volume 2 --autostart no") || args[0] != "install-local" {
			t.Fatal(args)
		}
		stage := args[2]
		if !strings.Contains(string(read(t, filepath.Join(stage, "app/ui/config"))), "My Demo") {
			t.Fatal("title lost")
		}
		if !strings.Contains(string(read(t, filepath.Join(stage, "app/ui/index.cgi"))), "watchcow-r") {
			t.Fatal("CGI lost")
		}
		if *fail {
			return []byte("[Error]Volume is unavailable."), nil
		}
		*installed = true
		return []byte("[Info]Installation complete."), nil
	}
}

func TestDesktopMigrationRegistersRealEntryAndIsIdempotent(t *testing.T) {
	d, id := desktopFixture(t)
	installed, fail := false, false
	calls := 0
	d.Run = fakeDesktopRun(t, d, &installed, &calls, &fail)
	if err := d.Sync(context.Background(), id); err != nil {
		t.Fatal(err)
	}
	if calls != 1 {
		t.Fatal(calls)
	}
	if _, err := os.Stat(filepath.Join(d.Dir, "backup/desktop", id+".json")); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(d.Dir, "desktop/pending", id)); !os.IsNotExist(err) {
		t.Fatal("completed stage retained", err)
	}
	if err := d.Sync(context.Background(), id); err != nil {
		t.Fatal(err)
	}
	if calls != 1 {
		t.Fatal("reinstalled an already registered entry", calls)
	}
}

func TestDesktopPendingRecoversAfterPackageDisappears(t *testing.T) {
	d, id := desktopFixture(t)
	installed, fail := false, true
	calls := 0
	d.Run = fakeDesktopRun(t, d, &installed, &calls, &fail)
	if err := d.Sync(context.Background(), id); err == nil {
		t.Fatal("accepted zero-exit CLI error")
	}
	if err := os.RemoveAll(filepath.Join(d.AppsDir, id)); err != nil {
		t.Fatal(err)
	}
	candidates, err := d.Candidates()
	if err != nil {
		t.Fatal(err)
	}
	if len(candidates) != 1 || candidates[0] != id {
		t.Fatal("lost interrupted package", candidates)
	}
	fail = false
	if err := d.Sync(context.Background(), id); err != nil {
		t.Fatal(err)
	}
	if calls != 2 {
		t.Fatal(calls)
	}
}

func TestDesktopMigrationRejectsModifiedControlAndExtraResources(t *testing.T) {
	for _, kind := range []string{"main", "callback", "resource", "manifest", "symlink"} {
		t.Run(kind, func(t *testing.T) {
			d, id := desktopFixture(t)
			live := filepath.Join(d.AppsDir, id)
			calls := 0
			switch kind {
			case "main":
				write(t, filepath.Join(live, "cmd/main"), append(read(t, filepath.Join(live, "cmd/main")), []byte("\ndocker restart Demo\n")...))
			case "callback":
				write(t, filepath.Join(live, "cmd/install_callback"), []byte("docker stop Demo\nexit 0\n"))
			case "resource":
				write(t, filepath.Join(live, "config/resource"), []byte(`{"docker-project":{}}`))
			case "manifest":
				write(t, filepath.Join(live, "manifest"), []byte("appname=watchcow.demo\ninstall_dep_apps=another-app\n"))
			case "symlink":
				if err := os.Symlink("/etc/passwd", filepath.Join(live, "target/ui/external")); err != nil {
					t.Fatal(err)
				}
			}
			installed, fail := false, false
			d.Run = fakeDesktopRun(t, d, &installed, &calls, &fail)
			if err := d.Sync(context.Background(), id); err == nil {
				t.Fatal("accepted unsafe package", kind)
			}
			if calls != 0 {
				t.Fatal("ran CLI for modified package")
			}
		})
	}
}

func TestDesktopMigrationCancellationAndInvalidIdentifier(t *testing.T) {
	d, id := desktopFixture(t)
	d.Run = func(context.Context, string, ...string) ([]byte, error) {
		t.Fatal("command after cancellation")
		return nil, fmt.Errorf("unexpected")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if err := d.Sync(ctx, id); err != context.Canceled {
		t.Fatal(err)
	}
	for _, id := range []string{"watchcow-r", "watchcow", "../other", "x';drop table entry;--"} {
		if err := d.Sync(context.Background(), id); err == nil {
			t.Fatal("accepted identifier", id)
		}
	}
}

func TestDesktopRegistryNormalizesPortlessLegacyEntries(t *testing.T) {
	d, _ := desktopFixture(t)
	d.Run = func(context.Context, string, ...string) ([]byte, error) {
		b, _ := json.Marshal([]desktopRegistration{{Name: "watchcow.demo", URL: `{"path":"/"}`}})
		return b, nil
	}
	same, err := d.registered(context.Background(), "watchcow.demo", map[string]map[string]interface{}{"watchcow.demo": {"protocol": "http", "url": "/"}})
	if err != nil || !same {
		t.Fatal("would repeatedly reinstall a hidden portless legacy icon", same, err)
	}
}

