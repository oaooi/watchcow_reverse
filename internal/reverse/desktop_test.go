func TestDesktopMigrationChecksVolumeBeforeUninstall(t *testing.T) {
	d, id := desktopFixture(t)
	installed, fail := false, false
	calls := 0
	d.Run = fakeDesktopRun(t, d, &installed, &calls, &fail)
	d.VolumeReady = func(int) error { return fmt.Errorf("volume offline") }
	if err := d.Sync(context.Background(), id); err == nil {
		t.Fatal("unavailable volume accepted")
	}
	if calls != 0 {
		t.Fatal("uninstalled desktop package before checking the volume")
	}
	if _, err := os.Stat(filepath.Join(d.AppsDir, id, "manifest")); err != nil {
		t.Fatal("original package lost", err)
	}
}
