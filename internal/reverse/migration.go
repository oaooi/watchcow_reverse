type fileBackup struct {
	Path        string `json:"path"`
	Original    []byte `json:"original"`
	Mode        uint32 `json:"mode"`
	Existed     bool   `json:"existed"`
	WrittenHash string `json:"written_hash"`
}
type journal struct {
	Started    bool                  `json:"started"`
	Prepared   bool                  `json:"prepared"`
	OldRunning bool                  `json:"old_running"`
	Files      map[string]fileBackup `json:"files"`
}

func digest(data []byte) string { h := sha256.Sum256(data); return hex.EncodeToString(h[:]) }
func (m *Manager) saveJournal() error {
	b, err := json.MarshalIndent(m.journal, "", "  ")
	if err != nil {
		return err
	}
	return atomicWrite(filepath.Join(m.Dir, "backup", "migration.json"), b, 0600)
}

// trackedWrite records both the previous content and the intended hash before
// the mutation. A crash between these writes still permits safe recovery.
func (m *Manager) trackedWrite(path string, data []byte, mode os.FileMode) error {
	old, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if string(old) == string(data) && err == nil {
		if rec, ok := m.journal.Files[path]; ok && rec.WrittenHash != digest(data) {
			rec.WrittenHash = digest(data)
			m.journal.Files[path] = rec
			return m.saveJournal()
		}
		return nil
	}
	rec, ok := m.journal.Files[path]
	if ok && strings.HasSuffix(path, "/index.cgi") && err == nil && digest(old) != rec.WrittenHash && digest(old) != digest(rec.Original) {
		return fmt.Errorf("CGI 脚本发生外部修改，保留文件: %s", path)
	}
	if !ok {
		rec = fileBackup{Path: path, Original: old, Existed: err == nil, Mode: uint32(mode.Perm())}
		if info, err := os.Stat(path); err == nil {
			rec.Mode = uint32(info.Mode().Perm())
		}
	}
	rec.WrittenHash = digest(data)
	m.journal.Files[path] = rec
	if err := m.saveJournal(); err != nil {
		return err
	}
	return atomicWrite(path, data, mode)
}

func oldWatchcowRunning() bool {
	data, err := os.ReadFile("/var/apps/watchcow/var/app.pid")
	if err != nil {
		return false
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(data)))
	if err != nil || pid <= 1 {
		return false
	}
	cmd, err := os.ReadFile(fmt.Sprintf("/proc/%d/cmdline", pid))
	return err == nil && strings.Contains(string(cmd), "/watchcow") && !strings.Contains(string(cmd), "/watchcow-r")
}

func controlOld(action string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, "appcenter-cli", action, "watchcow").CombinedOutput()
	if err != nil {
		return fmt.Errorf("旧 WatchCow %s 失败: %w: %s", action, err, out)
	}
	return nil
}

func (m *Manager) Prepare() error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.settings.Domain == "" {
		return fmt.Errorf("尚未配置基础域名")
	}
	// Validate before stopping the original watcher. No business container is
	// ever stopped, restarted or recreated by migration.
	if _, err := m.Native.Layout(); err != nil {
		return err
	}
	if m.Native.Run == nil && !m.Native.Extended {
		if err := m.Native.verifyBinary(); err != nil {
			return err
		}
		if !m.settings.NativeExtensions && !m.modeControl().Extended() {
			return fmt.Errorf("%w：在应用配置中将扩展授权设为 true", ErrExtensionConsent)
		}
	}
	if !m.journal.Started && !m.journal.Prepared {
		m.journal.OldRunning = m.oldRunning()
		m.journal.Started = true
		if err := m.saveJournal(); err != nil {
			return err
		}
	}
	if m.oldRunning() {
		if err := m.controlOld("stop"); err != nil {
			return err
		}
		if m.oldRunning() {
			return fmt.Errorf("旧 WatchCow 仍在运行，停止迁移")
		}
	}
	if !m.journal.Prepared {
		for _, name := range []string{"dashboard.gob", "label-revisions.json"} {
			source := filepath.Join(m.AppsDir, "watchcow", "etc", name)
			b, err := os.ReadFile(source)
			if errors.Is(err, os.ErrNotExist) {
				continue
			}
			if err != nil {
				return err
			}
			if err := atomicWrite(filepath.Join(m.Dir, "backup", "old-"+name), b, 0600); err != nil {
				return err
			}
			path := filepath.Join(m.Dir, name)
			if _, err := os.Stat(path); os.IsNotExist(err) {
				if err := atomicWrite(path, b, 0600); err != nil {
					return err
				}
			}
		}
	}
	if !m.journal.Prepared {
		entries, err := os.ReadDir(m.AppsDir)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			id := entry.Name()
			if id == AppID {
				continue
			}
			cmd, err := os.ReadFile(filepath.Join(m.AppsDir, id, "cmd", "main"))
			if err != nil {
				continue
			}
			if id == "watchcow" || strings.Contains(string(cmd), "Generated by WatchCow") {
				if err := m.archiveApp(id); err != nil {
					return err
				}
			}
		}
	}
	m.journal.Prepared = true
	if err := m.saveJournal(); err != nil {
		return err
	}
	return m.EnsureExtensions()
}

// archiveApp keeps the complete generated target (icons/CGI/config included),
// manifest and control scripts before changing an existing desktop entry.
func (m *Manager) archiveApp(id string) error {
	if !regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9_.-]{2,31}$`).MatchString(id) {
		return fmt.Errorf("unsafe app identifier")
	}
	path := filepath.Join(m.Dir, "backup", "packages", id+".tar.gz")
	if _, err := os.Stat(path); err == nil {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".package-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	_ = f.Chmod(0600)
	gz := gzip.NewWriter(f)
	tw := tar.NewWriter(gz)
	for _, name := range []string{"target", "cmd", "config", "manifest"} {
		root, err := filepath.EvalSymlinks(filepath.Join(m.AppsDir, id, name))
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			tw.Close()
			gz.Close()
			f.Close()
			return err
		}
		err = filepath.Walk(root, func(path string, info os.FileInfo, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			rel, err := filepath.Rel(root, path)
			if err != nil {
				return err
			}
			link := ""
			if info.Mode()&os.ModeSymlink != 0 {
				link, err = os.Readlink(path)
				if err != nil {
					return err
				}
			}
			h, err := tar.FileInfoHeader(info, link)
			if err != nil {
				return err
			}
			h.Name = filepath.Join(name, rel)
			if err := tw.WriteHeader(h); err != nil {
				return err
			}
			if info.Mode().IsRegular() {
				src, err := os.Open(path)
				if err != nil {
					return err
				}
				_, err = io.Copy(tw, src)
				src.Close()
				return err
			}
			return nil
		})
		if err != nil {
			tw.Close()
			gz.Close()
			f.Close()
			return err
		}
	}
	if err := tw.Close(); err != nil {
		gz.Close()
		f.Close()
		return err
	}
	if err := gz.Close(); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

// Rollback only restores a file whose content is still owned by this app.
// Subsequent user/OS edits are preserved and reported instead of clobbered.
func (m *Manager) Rollback() error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if err := m.RecoverDesktopPending(context.Background()); err != nil {
		return err
	}
	if err := m.Native.Apply(nil, true, true); err != nil {
		return err
	}
	var problems []error
	paths := make([]string, 0, len(m.journal.Files))
	for p := range m.journal.Files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, path := range paths {
		rec := m.journal.Files[path]
		b, err := os.ReadFile(path)
		if os.IsNotExist(err) {
			// A child uninstalled through fnOS must not be recreated by rollback.
			rel, relErr := filepath.Rel(m.AppsDir, path)
			parts := strings.Split(rel, string(filepath.Separator))
			if relErr == nil && len(parts) > 1 && parts[0] != ".." {
				if _, appErr := os.Stat(filepath.Join(m.AppsDir, parts[0])); os.IsNotExist(appErr) {
					continue
				}
			}
		}
		if os.IsNotExist(err) && !rec.Existed {
			continue
		}
		if err != nil {
			problems = append(problems, err)
			continue
		}
		if digest(b) == digest(rec.Original) && rec.Existed {
			continue
		}
		if digest(b) != rec.WrittenHash {
			problems = append(problems, fmt.Errorf("保留外部修改: %s", path))
			continue
		}
		if rec.Existed {
			err = atomicWrite(path, rec.Original, os.FileMode(rec.Mode))
		} else {
			err = os.Remove(path)
		}
		if err != nil {
			problems = append(problems, err)
		}
	}
	if len(problems) > 0 {
		return errors.Join(problems...)
	}
	// Restoring the files does not restore fnOS's persisted desktop registry.
	// Re-register the restored launchers before removing the CGI provider.
	ids := map[string]bool{}
	for _, path := range paths {
		rel, err := filepath.Rel(m.AppsDir, path)
		parts := strings.Split(rel, string(filepath.Separator))
		if err == nil && len(parts) > 1 && desktopID.MatchString(parts[0]) && parts[0] != AppID && parts[0] != "watchcow" {
			if _, err := os.Stat(filepath.Join(m.AppsDir, parts[0])); err == nil {
				ids[parts[0]] = true
			}
		}
	}
	for id := range ids {
		if err := m.SyncDesktop(context.Background(), id); err != nil {
			return err
		}
	}
	if err := m.restoreMode(true); err != nil {
		return err
	}
	if m.journal.OldRunning && !m.oldRunning() {
		if err := m.controlOld("start"); err != nil {
			return err
		}
	}
	m.journal = journal{Files: map[string]fileBackup{}}
	m.routes = map[string]Route{}
	if err := m.saveRoutes(); err != nil {
		return err
	}
	return m.saveJournal()
}
